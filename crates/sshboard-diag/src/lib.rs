//! 何が起きたかの記録。**人にも AI にも読める形で残します。**
//!
//! 帯（`sshboard-band`）とは役割が違います。
//!
//! | | 帯 | ここ |
//! |---|---|---|
//! | 何を | **誰が何をしたか**（人と AI の操作） | **なぜそうなったか**（技術的な経過） |
//! | 誰へ | 画面を見ている人 | 人と、詰まったときの AI |
//! | 受け取り待ち | する（D16） | **しない**（記録が実行を止めてはいけない） |
//!
//! **繋がらないときに、何を試して何が返ったかが残っていないと、人も AI も手が出ません。**
//! 実際に「認証が通りません」だけを見せて行き止まりにしました。
//!
//! ## 入れてよいもの・いけないもの
//!
//! | 入れる | 入れない |
//! |---|---|
//! | 接続の**識別子**（`web-prod`） | **ホスト名・IP・利用者名**（PRD §8） |
//! | 鍵の**指紋**と方式（秘密ではない） | 鍵の中身・パスフレーズ・鍵の**コメント**（パスやメールが入る） |
//! | 段階・所要時間・エラーの種類 | 合言葉・トークン |
//!
//! 入れてはいけないものが混ざっていないかは、`tests/redaction.rs` が見張っています。

