//! 画面を撮る口（D26）。**実装はここに置きません。**
//!
//! 撮れるのは画面を持っている側（Tauri）だけなので、ここは**穴**だけを開けます。
//! MCP の crate がウィンドウの都合を知ると、テストがウィンドウ無しで走らなくなります。
//!
//! ## なぜ「撮る前に伏せる」なのか
//!
//! **この製品は画面そのものに接続先が写り込みます**（CLAUDE.md 禁止事項 4）。
//! 撮ってから画像を加工する形にすると、**伏せていない元画像が一瞬でも存在します。**
//! 先に画面側（CSS）で伏せてしまえば、**伏せていない画素は最初から作られません。**
//!
//! 伏せるのは**中身**であって**形ではありません。**
//! 大きさ・位置・重なり・はみ出しは残ります。**残さないと崩れが見つかりません。**

use std::future::Future;
use std::pin::Pin;

/// 撮れた 1 枚。**接続先の文字列は入っていません**（画素と寸法だけ）。
#[derive(Debug, Clone)]
pub struct WindowShot {
    /// PNG のバイト列。
    pub png: Vec<u8>,
    /// ウィンドウの題。**製品名だけ**が入る想定（接続先を題に出さない）。
    pub title: String,
    /// 縮める前の大きさ。**崩れの判断に要る**（実寸が分からないと比べられない）。
    pub width: u32,
    pub height: u32,
    /// 返した画像の大きさ。
    pub scaled_width: u32,
    pub scaled_height: u32,
    /// **伏せて撮ったか。**返り値に必ず添えます（伏せ忘れを見逃さないため）。
    pub redacted: bool,
}

/// 画面を 1 枚撮る。
///
/// `redact` が真なら、**伏せ終わったことを確かめてから**撮ること。
/// 確かめずに撮ると、伏せる仕組みが在っても中身が写ります。
pub trait WindowCapture: Send + Sync {
    /// `max_edge` は返す画像の長辺（画素）。**引き伸ばしはしません。**
    fn capture<'a>(
        &'a self,
        redact: bool,
        max_edge: u32,
    ) -> Pin<Box<dyn Future<Output = Result<WindowShot, String>> + Send + 'a>>;
}
