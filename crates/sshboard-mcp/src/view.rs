//! 人の画面を「こちらを見てください」と動かす口（D44 / Issue #15）。
//!
//! **実装はここに置きません。**画面を持っているのは Tauri 側だけなので、
//! ここは**穴**だけを開けます（`capture.rs` と同じ形）。
//! MCP の crate がウィンドウの都合を知ると、テストがウィンドウ無しで走らなくなります。
//!
//! ## これで増えないもの
//!
//! **承認も実行も増えません。**AI にできるのは「見てください」と言うことだけで、
//! **画面が動くかどうかを決めるのは画面の側**です。
//!
//! 人が何かしている最中（問いが出ている・入力欄に焦点・直前に自分で切り替えた）は、
//! **頼まれても動きません。**そこの判定は `apps/desktop` の `view-request.ts` にあります。
//!
//! ## なぜ口を開けたか
//!
//! 実機で、AI が端末で打っている間ずっと人は［接続］タブに居ました。
//!
//! > **AI 側には「こちらを見てください」と言う手段がありません。**
//! > チャットで「端末タブを開いてください」と書くことはできますが、
//! > それは**この製品が消したかったはずの往復**そのものです。
//!
//! `focus_connection` は**操作の宛先**を変えるもので、**人が見ている画面は動きません。**

use std::future::Future;
use std::pin::Pin;

/// 画面のタブ。**画面側の呼び名と 1 つに揃えます**（D44）。
///
/// `terminal` ではなく `console`、`activity` / `log` ではなく `band` / `diag`。
/// **MCP へ出した値は後から変えにくい**ので、ここで揃えておきます。
pub const VIEWS: [&str; 5] = ["connections", "files", "console", "band", "diag"];

/// 画面を切り替える口。**画面を持っている側が実装します。**
pub trait ShowView: Send + Sync {
    /// 「こちらを見てください」と伝える。
    ///
    /// **届いたことしか保証しません。**実際に切り替わるかは画面の側が決めます
    /// （人が何かしている最中なら動きません）。
    fn show<'a>(
        &'a self,
        view: &'a str,
    ) -> Pin<Box<dyn Future<Output = Result<(), String>> + Send + 'a>>;
}
