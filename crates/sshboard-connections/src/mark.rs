//! 接続に付ける印 — **色とタグ**。
//!
//! dbboard の `mark.rs` からの移植（D5）。設計の理由もそちらに合わせている。
//!
//! **色は「名前」で持ちます。16 進数で持ちません。**
//!
//! - **名前は、色が見えないときに使える。**読み上げ・口頭・メモ。`#1a73e8` はどれでもない
//! - 明るい行と暗い行で要る値が違う。**名前なら配色側が選べる。**
//!   16 進数を書くと、片方のテーマが設定ファイルに焼き付く
//! - **8 色。**本番と複製を一目で見分けるには足り、かつ全部が互いに区別できる
//!
//! **タグは色の相棒で、白黒のスクリーンショットでも色覚特性のある人にも効く方**です。
//! 決め打ちの一覧ではなく自由文にしてあります。**チームが自分のサーバーを呼ぶ言葉は、
//! ここで列挙できるものではない。**

/// 付けられる色。**並び順は選択画面に出る順**（スペクトル順なので、
/// 名前を読まなくても「緑のやつ」を探せる）。
///
/// **16 色。**dbboard は 8 色だが、こちらは対象サーバーが 13 台以上あり、
/// 8 だと色がぶつかる（実測・2026-08-27）。
/// 増やすほど 1 色ずつの区別は付きにくくなるので、**タグと併せて使う前提**。
pub const CONNECTION_COLORS: [&str; 16] = [
    "red", "orange", "amber", "yellow", "lime", "green", "emerald", "teal", "cyan", "sky", "blue",
    "indigo", "violet", "purple", "magenta", "pink",
];

/// タグの上限。**バイトではなく文字数で数える。**
///
/// 漢字 12 文字は 36 バイトだが、ラテン 12 文字より行の幅を食わない。
/// バイトで測ると**短い方のラベルを弾いてしまう。**
pub const CONNECTION_TAG_MAX_CHARS: usize = 12;

/// `name` が [`CONNECTION_COLORS`] のどれかか。
///
/// **大文字小文字を区別します。**保存される値はこの並びのどれかであって、
/// 人が打った言葉ではありません。`"Blue"` を通すと、
/// **対応する配色の定義が無い値がファイルに入ります。**
pub fn is_connection_color(name: &str) -> bool {
    CONNECTION_COLORS.contains(&name)
}

/// タグが行に載る長さか。**空は「タグ無し」として通します。**
pub fn is_connection_tag(tag: &str) -> bool {
    tag.chars().count() <= CONNECTION_TAG_MAX_CHARS
}
