//! **AI が呼べるコマンドの許可リスト**（D3）。
//!
//! `run_command(cmd)` を作らないための片割れです。AI が渡せるのは
//! **人が書いた一覧の中の識別子だけ**で、引数で文字列をシェルへ渡す口がありません。
//! 実際に走るのは、人が `readonly.toml` に書いた文字列そのものです。
//!
//! ## 名前が言い切れないこと
//!
//! **製品は「そのコマンドが本当に読み取り専用か」を検証できません。**
//! `uptime` と `rm -rf /` を機械が見分ける方法はありません。
//! ここが守るのは「**AI が自分で文字列を組み立てられない**」ことだけで、
//! 何を許すかは人が書いた一覧が決めます。
//!
//! ## 既定は空
//!
//! **この crate は既定のコマンドを 1 本も持ちません**（D3 追記・2026-08-27）。
//! いま誰も、実務でどのコマンドが要るかの一覧を持っていません。
//! 推測で書けば必ず外し、多すぎれば D3 の意味が消え、少なすぎれば作業が止まります。
//!
//! 代わりに、**断った事実を機械が残します**（[`Refusals`]）。
//! 何が足りなかったかは記録が出し、**足す判断は人**がします。

