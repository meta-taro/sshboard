/**
 * **帯を書き出す**（案・4 枚目「AI の操作記録（帯）を書き出す」）。
 *
 * ## なぜ要るか
 *
 * 帯には、人と AI の操作が時間順に 1 本で並びます。
 * **何が起きたかを後から人へ渡せるのは、ここだけ**です
 * （実行体は帯を貯めません。控えは画面が持っています）。
 *
 * ## 囲いは、ここを守りません
 *
 * **落とし先は人の手元です。**D22 の柵は 1 ミリも守りません ——
 * D27 で「手元へ落とす口は AI に作らない」と決めたのと同じ性質です。
 *
 * だから **この口は画面にしか置きません。**MCP には出しません。
 * AI は `read_stream` で同じ流れを読めます ——
 * **ファイルにする必要があるのは人だけ**です。
 *
 * ## 何が入るかを、押す前に見せます
 *
 * **帯には接続の識別子とサーバー側のパスが入ります**（`connect web-01`・
 * `/srv/app/releases`）。書き出した文を公開の場へ貼ると、
 * **接続先が出ます**（禁止事項 4）。だから中身を並べて見せてから書きます。
 *
 * ## 伏せているときは、伏せたまま書きます
 *
 * 画面を伏せた状態で書き出すと、**画面と同じものが出ます。**
 * 「見えているものと、書き出したものが違う」を作りません ——
 * 読める形で要るなら、人が伏せを解いてから押します。
 */

import type { BandLine } from './band';

/** 伏せたときに置き換える文字。**長さも伏せます**（字数から推測されないように）。 */
const HIDDEN = '●●●●●';

/** 書き出しの頭に付ける断り。**貼る前に読まれる所に置きます。** */
export const EXPORT_HEADER = [
	'# sshboard — 人と AI の操作記録（帯）',
	'#',
	// **記号を書きません。**これは素のテキストで、`**` を描く物は何もありません
	// （このリポの文言の決まりと同じ理由。`messages.test.ts` が画面の文言で見張っています）。
	'# 接続の識別子とサーバー側のパスが入っています。',
	'# 公開の場（Issue・チャット・ブログ）へそのまま貼らないでください。'
].join('\n');

export type ExportOptions = {
	/** 画面を伏せているか。**伏せているなら、書き出しも伏せます。** */
	masked: boolean;
	/** 書いた時刻（試験から渡せるように）。 */
	at?: Date;
};

/**
 * 書き出す文を組む。
 *
 * **画面と同じ並び・同じ中身。**並べ替えも、間引きもしません ——
 * 書き出したものが画面と違うと、**どちらが本当か分からなくなります。**
 */
export function bandExportText(
	lines: readonly BandLine[],
	{ masked, at = new Date() }: ExportOptions
): string {
	const head = [EXPORT_HEADER, `# ${at.toISOString()} — ${lines.length} 行`];
	if (masked) {
		// **伏せていることを書いておく。**後から読む人が
		// 「●」を壊れたファイルだと思わないように。
		head.push('# 画面を伏せた状態で書き出しました。中身は伏せてあります。');
	}
	const body = lines.map((line) => (masked ? `${line.tag} ${HIDDEN}` : line.rendered));
	return [...head, '', ...body].join('\n') + '\n';
}

/** 落とすときの既定の名前。**日時を入れます** —— 同じ名前だと 2 回目から上書きです。 */
export function defaultBandName(at = new Date()): string {
	const stamp = at.toISOString().replace(/[:.]/g, '-').slice(0, 19);
	return `sshboard-band-${stamp}.txt`;
}
